// Builds the CSS of @pacod/ui from tokens/*.json:
// - tokens.css: the canonical custom properties (--pid-*), light and dark through light-dark(),
//   [data-theme] to force one scheme, and [data-brand] blocks for the brands;
// - console.css: unprefixed names (--bg, --accent, …) for plain-CSS apps, as aliases of the
//   canonical ones, so an app's own stylesheet keeps only its layout rules;
// - tailwind.css: an @theme inline block that maps Tailwind theme names (--color-surface,
//   --color-brand, …) onto the canonical ones.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const HEADER =
	'/* Generated by @pacod/ui (scripts/build-tokens.js) from tokens/*.json. Do not edit. */\n';

export function readTokens(dir) {
	const read = (name) => JSON.parse(readFileSync(join(dir, name), 'utf8'));
	return { base: read('base.json'), color: read('color.json'), brands: read('brands.json') };
}

const entries = (o) => Object.entries(o).filter(([k]) => !k.startsWith('$'));
const pair = ([light, dark]) => (light === dark ? light : `light-dark(${light}, ${dark})`);

/** Tokens computed from others; written again wherever a brand changes their inputs. */
function derived() {
	return [
		['info', 'var(--pid-accent)'],
		['info-soft', 'var(--pid-accent-soft)'],
		['focus', 'var(--pid-accent)'],
		['focus-ring', '0 0 0 3px color-mix(in srgb, var(--pid-accent) 18%, transparent)'],
		['shadow-sm', '0 8px 24px -12px light-dark(rgb(19 33 29 / 0.18), rgb(0 0 0 / 0.6))'],
		['shadow', '0 24px 48px -16px light-dark(rgb(19 33 29 / 0.28), rgb(0 0 0 / 0.7))'],
		['backdrop', 'rgb(0 0 0 / 0.55)']
	];
}

const line = (name, value) => `\t--pid-${name}: ${value};`;

export function tokensCss({ base, color, brands }) {
	const out = [HEADER, ':root {', '\tcolor-scheme: light dark;'];
	for (const [, group] of entries(base)) {
		for (const [name, value] of entries(group)) out.push(line(name, value));
	}
	for (const [name, values] of entries(color)) out.push(line(name, pair(values)));
	for (const [name, value] of derived()) out.push(line(name, value));
	out.push('}', '');
	out.push(":root[data-theme='light'] {", '\tcolor-scheme: light;', '}', '');
	out.push(":root[data-theme='dark'] {", '\tcolor-scheme: dark;', '}', '');
	for (const [brand, b] of entries(brands)) {
		if (!b.font && !b.color) continue;
		out.push(`:root[data-brand='${brand}'],`, `[data-brand='${brand}'] {`);
		for (const [name, value] of entries(b.font ?? {})) out.push(line(name, value));
		for (const [name, values] of entries(b.color ?? {})) out.push(line(name, pair(values)));
		for (const [name, value] of derived()) out.push(line(name, value));
		out.push('}', '');
	}
	return out.join('\n');
}

/** The console's names, all of which alias a canonical token of the same name. */
export function consoleNames({ base, color }) {
	const names = [];
	for (const [, group] of entries(base)) for (const [name] of entries(group)) names.push(name);
	for (const [name] of entries(color)) names.push(name);
	for (const [name] of derived()) names.push(name);
	return names;
}

export function consoleCss(tokens) {
	const out = [
		HEADER,
		'/* Unprefixed names for plain-CSS apps. Every one is an alias of the canonical --pid-',
		'   token, so a brand set on the root reaches the app as well. */',
		':root,',
		'[data-brand] {'
	];
	for (const name of consoleNames(tokens)) {
		const alias = name === 'font' ? 'font' : name;
		out.push(`\t--${alias}: var(--pid-${name});`);
	}
	out.push('}', '');
	return out.join('\n');
}

