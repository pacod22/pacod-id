// Writes a TypeScript module from a product manifest: the manifest itself, a catalogue holding
// it, and union types of its roles, permissions and scope types, so that code checking
// permissions is typed against the manifest instead of strings that can drift from it.

import { Manifest, ORGANISATION, PLATFORM, type ManifestSource } from './manifest.js';
import { compare } from './manifest.js';

/** The exact permission names a manifest mentions: role permissions, grant and bypass ones. */
function permissionNames(m: Manifest): string[] {
	const names = new Set<string>();
	for (const role of m.roles()) {
		for (const p of m.source.roles?.[role.name.slice(m.product.length + 1)]?.permissions ?? []) {
			if (p !== '*' && !p.endsWith('.*')) names.add(`${m.product}.${p}`);
		}
		if (role.protection?.kind === 'bypass') names.add(role.protection.permission);
		names.add(m.grantPermission(role.name));
	}
	names.add(m.grantPermission(`${m.product}.custom`));
	return [...names].sort(compare);
}

const union = (values: string[]) =>
	values.length === 0 ? 'never' : values.map((v) => `'${v}'`).join(' | ');

/** The source of the generated module. `from` names the manifest file in the header. */
export function generate(manifest: Manifest, from: string, importFrom = '@pacod/id-authz'): string {
	const source: ManifestSource = manifest.source;
	const roles = manifest.roles().map((r) => r.name);
	const scopeTypes = [PLATFORM, ORGANISATION, ...manifest.scopeTypes().map(([k]) => k)];
	return [
		`// Generated by \`pacod-id-authz gen\` from ${from}. Do not edit; run the generator again.`,
		'',
		`import { Catalog, Manifest, type ManifestSource } from '${importFrom}';`,
		'',
		`export const PRODUCT = '${manifest.product}';`,
		'',
		`export const manifestSource: ManifestSource = ${JSON.stringify(source, null, '\t')};`,
		'',
		'export const manifest = Manifest.fromSource(manifestSource);',
		'',
		'/** A catalogue holding only this product; products may add manifests of others. */',
		'export const catalog = new Catalog().with(manifest);',
		'',
		`export type Role = ${union(roles)};`,
		'',
		`export const ROLES: readonly Role[] = ${JSON.stringify(roles)};`,
		'',
		`export type Permission = ${union(permissionNames(manifest))};`,
		'',
		`export type ScopeType = ${union(scopeTypes)};`,
		''
	].join('\n');
}
